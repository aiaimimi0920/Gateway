import { chromium } from "playwright";
const baseUrl = process.env.PROBE_BASE_URL ?? "http://localhost:4200/ui/";
const token = process.env.PROBE_TOKEN ?? "123456";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
await page.goto(baseUrl, { waitUntil: "domcontentloaded" });
await page.getByLabel("管理密钥").fill(token);
await page.getByRole("button", { name: "登录" }).click();
await page.getByRole("button", { name: "权益组", exact: true }).click();
await page.waitForTimeout(1500);
await page.screenshot({ path: "output/compare-groups-front.png" });
await page.getByRole("button", { name: "模型池", exact: true }).click();
await page.waitForTimeout(1500);
const card = page.locator('[data-model-pool-card="qwen3-coder-plus"]');
await card.scrollIntoViewIfNeeded();
await page.waitForTimeout(400);
console.log("primary cell:", await card.locator('[data-model-pool-metric="primary"]').textContent());
console.log("primary lines:", await card.locator('[data-model-pool-metric="primary"]').evaluate((n) => n.getClientRects().length));
console.log("primary dt lines:", await card.locator('[data-model-pool-metric="primary"]').evaluate((n) => n.previousElementSibling.getClientRects().length));
await page.screenshot({ path: "output/compare-models-front.png" });
await browser.close();
